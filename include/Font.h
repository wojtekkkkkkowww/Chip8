#pragma once

#include <algorithm>
#include <array>
#include <cstdint>

namespace Font {

inline constexpr uint16_t START_ADDRESS = 0x50;
inline constexpr uint8_t BYTES_PER_GLYPH = 5;

// Standard CHIP-8 font, copied from Tobias V. I. Langhoff's reference:
// https://tobiasvl.github.io/blog/write-a-chip-8-emulator/#font
inline constexpr std::array<uint8_t, 80> DATA = {
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80  // F
};

inline void loadInto(std::array<uint8_t, 4096> &ram) {
    std::copy(DATA.begin(), DATA.end(), ram.begin() + START_ADDRESS);
}

} // namespace Font
